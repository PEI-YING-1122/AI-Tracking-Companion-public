"""Create directory junctions from the fixture origins to the external test data.

    python scripts/link_fixture_origins.py [--remove]

Fixture HIP files (generated by upstream build_houdini_scene) contain the absolute
paths of the folder they were generated in, written with backslashes, which
HOUDINI_PATHMAP does not map.  Instead of editing the HIP files, each origin listed
in <test data root>/fixture_origins.json becomes a junction to the fixture's
current location.  Junctions hold no data; --remove deletes only the junctions.
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tests"))
import test_paths as tp  # noqa: E402


def is_junction(p):
    try:
        return os.path.isjunction(p) if hasattr(os.path, "isjunction") else os.readlink(p) is not None
    except OSError:
        return False


def main():
    remove = "--remove" in sys.argv
    for origin, target in tp.fixture_origins().items():
        o = os.path.normpath(origin)
        if remove:
            if is_junction(o):
                os.rmdir(o)  # removes the link only
                print("removed", o)
            continue
        if os.path.exists(o):
            print(("ok      " if os.path.samefile(o, target) else "CONFLICT") + f" {o}")
            continue
        os.makedirs(os.path.dirname(o), exist_ok=True)
        subprocess.run(["cmd", "/c", "mklink", "/J", o, os.path.normpath(target)], check=True, capture_output=True)
        print("linked  ", o, "->", target)


if __name__ == "__main__":
    main()
